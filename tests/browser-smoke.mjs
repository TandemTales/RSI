// Optional browser QA. Uses an existing Playwright installation; no downloads.
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE || 'C:/Python312/Lib/site-packages/playwright/driver/package');
const url = process.env.RSI_URL || 'http://127.0.0.1:4174';
const evidence = process.env.RSI_EVIDENCE_DIR || '.preview';
await mkdir(evidence, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || 'C:/Users/jshun/AppData/Local/ms-playwright/chromium-1155/chrome-win/chrome.exe', timeout: 20000 });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, reducedMotion: 'reduce' });
const errors = [], failedRequests = [], checks = [];
page.on('pageerror', e => errors.push(e.message));
page.on('response', response => { if (response.status() >= 400) failedRequests.push(`${response.status()} ${response.url()}`); });
const snapshot = () => page.evaluate(() => window.rsi.snapshot());
const check = name => { checks.push(name); console.log(`PASS ${name}`); };
async function clickSteps(n) { for(let i=0;i<n;i++) await page.locator('#step').click(); }
try {
  await page.goto(url, { timeout: 20000 });
  await page.waitForFunction(() => window.rsi);
  assert.equal(await page.title(), 'RSI — Recursive Self-Improvement');
  assert.equal((await snapshot()).robots.length, 1);
  assert.equal(await page.locator('#mode').innerText(), 'PAUSED');
  await page.screenshot({ path: `${evidence}/desktop-initial.png`, fullPage: true });
  check('initial paused game renders');
  await page.locator('#speed').selectOption('8');
  await page.locator('#run').click();
  await page.waitForFunction(() => window.rsi.snapshot().tick >= 3);
  await page.locator('#run').click();
  const pausedTick = (await snapshot()).tick;
  await page.waitForTimeout(220);
  assert.equal((await snapshot()).tick, pausedTick);
  await page.locator('#step').click();
  assert.equal((await snapshot()).tick, pausedTick + 1);
  check('run, pause, speed and single step work');
  await page.locator('#reset').click();
  assert.equal((await snapshot()).bin, 18);
  await clickSteps(112);
  const established = await snapshot();
  assert.equal(established.goalTick,112);
  assert.equal(established.robots.length,3);
  assert.ok(established.robots[1].deliveries > 0);
  assert.equal(await page.locator('.robot-card').count(),3);
  assert.match(await page.locator('#goal-status').innerText(), /LOOP ESTABLISHED/);
  await page.locator('[data-robot="2"]').click();
  assert.match(await page.locator('#debug-title').innerText(), /R02/);
  assert.match(await page.locator('#balance').innerText(), /18 \/ 18/);
  await page.screenshot({ path: `${evidence}/desktop-three-robots.png`, fullPage: true });
  check('default UI route builds R02 and R03 with R02 helping; selection/debug update');
  await page.locator('#reset').click();
  await page.locator('#child-program').selectOption('express');
  await clickSteps(64);
  assert.equal((await snapshot()).robots[1].program.name,'Express');
  await page.locator('#template').selectOption('express');
  await page.locator('#editor').fill('move 10 8\nmove 3 8\nmove 3 4\npick W\nmove 10 4\ndrop E\nactivate E\nrepeat');
  await page.locator('#save').click();
  assert.equal((await snapshot()).childProgram.version,2);
  assert.equal((await snapshot()).robots[1].program.version,1);
  check('child program choice and revision isolation work through the UI');
  await page.locator('#editor').fill('move 0 0\nrepeat');
  await page.locator('#deploy').click();
  assert.match(await page.locator('#editor-message').innerText(),/Line 1/);
  assert.equal((await snapshot()).robots[0].program.name,'Courier');
  check('invalid program produces a diagnostic and is not deployed');
  await page.locator('#jam').click();
  await page.locator('#step').click();
  assert.ok((await snapshot()).robots.every(r=>r.blocked));
  assert.match(await page.locator('#debug-status').innerText(),/Traffic/);
  await page.screenshot({ path: `${evidence}/desktop-jam.png`, fullPage: true });
  await page.locator('#template').selectOption('custom');
  await page.locator('#editor').fill('move 6 5\nmove 9 5\nrepeat');
  await page.locator('#deploy').click();
  await clickSteps(4);
  const detour=await snapshot();
  assert.equal(detour.robots[0].x,9);assert.equal(detour.robots[0].y,5);assert.equal(detour.robots[1].x,4);
  check('jam is visible and a user-edited detour resolves it');
  await page.locator('#factory').click();
  await page.locator('#child-program').selectOption('courier');
  await page.locator('#reset').click();
  assert.equal((await snapshot()).robots.length,1);assert.equal((await snapshot()).tick,0);
  for(const [width,height] of [[390,844],[320,740],[844,390]]){
    await page.setViewportSize({width,height});
    await page.evaluate(()=>scrollTo(0,0));
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`no overflow at ${width}`);
    await page.screenshot({path:`${evidence}/viewport-${width}x${height}.png`,fullPage:true});
    await page.locator('#step').click();
  }
  check('390px, 320px and landscape layouts have no horizontal overflow; controls work');
  assert.deepEqual(errors,[]);assert.deepEqual(failedRequests,[]);
  check('no browser JavaScript errors or HTTP failures');
  await writeFile(`${evidence}/browser-report.json`,JSON.stringify({url,browser:browser.version(),checks,errors,failedRequests},null,2));
} finally { await browser.close(); }
